"""Generate a Souffle execution-fusion program from an OCEL log.

Inputs: a log, the identity types (each generates one execution), and a
list of (type, type) connections naming which other types hang off them.
The datalog rules are a fixed template; only facts/*.facts change per log.

    python ocel_to_datalog.py LOG.duckdb --out DIR --identity T \
        [--connect A:B ...] [--rename OLD:NEW ...] [--name N] [--run]
"""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path


def load_e2o(source, fmt="duckdb"):
    """Return (eid, object_type, object_id) triples. Add formats here later."""
    if fmt != "duckdb":
        raise ValueError(f"unsupported format: {fmt}")
    import duckdb

    con = duckdb.connect(str(source), read_only=True)
    rows = con.execute(
        "SELECT DISTINCT eid, object_type, object_id FROM log_e2o"
    ).fetchall()
    con.close()
    return [(str(e), str(t), str(o)) for e, t, o in rows]


def generate(source, identity_types, connections=(), out_dir=".", *,
             name=None, fmt="duckdb", renames=None, run=False):
    rn = (renames or {}).get
    identity = {rn(t, t) for t in identity_types}
    # a connector is any type named in a connection that isn't itself an identity type
    connectors = {rn(t, t) for pair in connections for t in pair} - identity
    binding = identity | connectors

    triples = [(e, rn(t, t), o) for e, t, o in load_e2o(source, fmt)]
    log_types = {t for _, t, _ in triples}
    unknown = (identity | connectors) - log_types
    if unknown:
        raise ValueError(f"types not in log: {sorted(unknown)}")

    out = Path(out_dir)
    facts = out / "facts"
    facts.mkdir(parents=True, exist_ok=True)

    def tsv(fname, rows):
        body = "".join("\t".join(r) + "\n" for r in sorted(set(rows)))
        (facts / fname).write_text(body)

    tsv("event.facts", [(e,) for e, _, _ in triples])
    tsv("participates.facts", [(o, e) for e, _, o in triples])
    tsv("type.facts", [(o, t) for _, t, o in triples])
    tsv("binding_type.facts", [(t,) for t in binding])
    tsv("identity_type.facts", [(t,) for t in identity])

    name = name or Path(str(source)).stem
    header = (
        f"// generated by ocel_to_datalog.py from {name}\n"
        f"// identity={sorted(identity)} connectors={sorted(connectors)} "
        f"resources={sorted(log_types - binding)}\n\n"
    )
    dl = out / f"{name}.dl"
    dl.write_text(header + TEMPLATE)

    if run:
        (out / "output").mkdir(exist_ok=True)
        subprocess.run(
            ["souffle", str(dl), "-F", str(facts), "-D", str(out / "output")],
            check=True,
        )
    return dl


TEMPLATE = r"""// ---- inputs ----
.decl event(e:symbol)
.input event
.decl participates(x:symbol, e:symbol)
.input participates
.decl type(x:symbol, t:symbol)
.input type
.decl binding_type(t:symbol)          // identity + connector types
.input binding_type
.decl identity_type(t:symbol)         // types that generate executions
.input identity_type

// ---- roles ----
.decl object(x:symbol)
object(x) :- type(x, _).
.decl binding(x:symbol)
binding(x) :- type(x, t), binding_type(t).
.decl resource(x:symbol)
resource(x) :- object(x), !binding(x).

// ---- identity criterion ----
// an event is ambiguous if two participants share a binding type: nobody is
// then "the" X of that event, so it establishes no links.
.decl ambiguous(e:symbol)
ambiguous(e) :- binding_type(t), participates(x, e), participates(y, e),
                ord(x) < ord(y), type(x, t), type(y, t).
.decl identifying(e:symbol)
identifying(e) :- event(e), !ambiguous(e).

// links between binding objects that meet in an identifying event
.decl link(x:symbol, y:symbol)
link(x, y) :- identifying(e), participates(x, e), participates(y, e),
              x != y, binding(x), binding(y).

// reflexive-transitive closure (cycle-safe under set semantics)
.decl kin(x:symbol, y:symbol)
kin(x, x) :- binding(x).
kin(x, y) :- link(x, y).
kin(x, z) :- kin(x, y), link(y, z).

// ---- fusion ----
.decl generator(x:symbol)
generator(x) :- type(x, t), identity_type(t).
.decl extent(x:symbol, y:symbol)
extent(x, y) :- generator(x), kin(x, y).
// the sum of x is the event set { e : part_of(e, x) }
.decl part_of(e:symbol, x:symbol)
part_of(e, x) :- extent(x, y), participates(y, e).
.decl has_sum(x:symbol)
has_sum(x) :- part_of(_, x).
.decl sum_size(x:symbol, n:number)
sum_size(x, n) :- has_sum(x), n = count : { part_of(_, x) }.

// two generators share a sum iff no event separates them (pruned by size)
.decl sum_differs(x:symbol, y:symbol)
sum_differs(x, y) :- sum_size(x, n), sum_size(y, n), x != y,
                     part_of(e, x), !part_of(e, y).
.decl same_sum(x:symbol, y:symbol)
same_sum(x, x) :- has_sum(x).
same_sum(x, y) :- sum_size(x, n), sum_size(y, n), x != y,
                  !sum_differs(x, y), !sum_differs(y, x).

// the least generator by ordinal is the execution's canonical name
.decl not_canonical(x:symbol)
not_canonical(x) :- same_sum(x, y), ord(y) < ord(x).
.decl execution(rep:symbol)
execution(rep) :- has_sum(rep), !not_canonical(rep).
.decl execution_event(rep:symbol, e:symbol)
execution_event(rep, e) :- execution(rep), part_of(e, rep).
.decl execution_size(rep:symbol, n:number)
execution_size(rep, n) :- execution(rep), sum_size(rep, n).

// executions that share only ambiguous events: they touch but do not merge
.decl exec_overlaps(a:symbol, b:symbol)
exec_overlaps(a, b) :- execution(a), execution(b), ord(a) < ord(b),
                       execution_event(a, e), execution_event(b, e).
.decl exec_shares_identifying(a:symbol, b:symbol)
exec_shares_identifying(a, b) :- exec_overlaps(a, b),
    execution_event(a, e), execution_event(b, e), identifying(e).
.decl externally_connected(a:symbol, b:symbol)
externally_connected(a, b) :- exec_overlaps(a, b), !exec_shares_identifying(a, b).

.output ambiguous
.output identifying
.output execution
.output execution_event
.output execution_size
.output same_sum
.output externally_connected
"""


def _pair(s):
    a, b = s.split(":", 1)
    return a, b


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", help="DuckDB log with a log_e2o(eid, object_type, object_id) table")
    ap.add_argument("--out", required=True)
    ap.add_argument("--identity", action="append", required=True, metavar="TYPE")
    ap.add_argument("--connect", action="append", default=[], type=_pair, metavar="A:B")
    ap.add_argument("--rename", action="append", default=[], type=_pair, metavar="OLD:NEW")
    ap.add_argument("--name")
    ap.add_argument("--run", action="store_true", help="also invoke souffle")
    a = ap.parse_args()

    dl = generate(a.source, a.identity, a.connect, a.out,
                  name=a.name, renames=dict(a.rename), run=a.run)
    print("wrote", dl)


if __name__ == "__main__":
    main()
